def translate(lang: str, key: str, **kwargs) -> str:
    """Übersetzt `key` in die gegebene Sprache. Fällt auf Deutsch, dann auf
    den Key selbst zurück, damit ein fehlender Key nie einen Fehler wirft."""
    lang = lang if lang in TRANSLATIONS else DEFAULT_LANGUAGE
    text = TRANSLATIONS[lang].get(key)
    if text is None:
        text = TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
    return text.format(**kwargs) if kwargs else text
